# Each example of this file runs the real code path that makes a translated string (textdomain
# "storage") of the vendored YaST code reach the issues sent by the D-Bus service, and checks that
# the (English) text is part of the JSON generated by the D-Bus layer.
#
# * AutoYaST storage issues: Y2Storage::AutoinstProposal -> Autoyast strategy (#agama_issue) ->
#   Agama::Storage::Manager#issues -> "Issues" D-Bus property.
# * Probing issues: Y2Storage::ProbedDevicegraphChecker -> Agama::Storage::Manager#probing_issues
#   -> "issues" key of the "System" D-Bus property.
#
# The string "Disk '%s' was not found" (and the other NoDisk string) is already covered by
# test/agama/storage/autoyast_translations_test.rb.
#
# See the report in service/translations.md.

require_relative "../test_helper"
require_relative "../agama/storage/storage_helpers"
require "agama/config"
require "agama/dbus/with_issues"
require "agama/storage/manager"
require "y2storage"
require "json"
require "yaml"

Yast::ProductFeatures.InitFeatures(true)

# Mimics the way the D-Bus layer (Agama::DBus::Storage::Manager) generates the issues.
class IssuesTestSerializer
  include Agama::DBus::WithIssues
end

describe "Translated storage issues returned by the D-Bus service" do
  include Agama::RSpec::StorageHelpers

  let(:logger) { Logger.new($stdout, level: :fatal) }

  let(:config) { Agama::Config.new(YAML.load_file(File.join(FIXTURES_PATH, "storage.yaml"))) }

  let(:arch) do
    instance_double(Y2Storage::Arch, x86?: true, efiboot?: true, ram_size: 4 * (1024**3))
  end

  let(:manager) do
    Agama::Storage::Manager.new(logger: logger).tap { |m| m.update_product_config(config) }
  end

  let(:serializer) { IssuesTestSerializer.new }

  # Whether Yast::Arch.x86_64 is true (it affects to bcache)
  let(:x86_64) { true }

  let(:scenario) { "windows-linux-pc.yml" }

  before do
    allow(Yast::Arch).to receive(:x86_64).and_return(x86_64)
    allow(Y2Storage::Arch).to receive(:new).and_return(arch)
    mock_storage(devicegraph: scenario)
  end

  describe "AutoYaST issues (legacyAutoyastStorage)" do
    # Make the result independent of the system running the tests
    before do
      allow(Y2Storage::EncryptionProcesses::SecureKey).to receive(:available?).and_return(false)
      allow_any_instance_of(Y2Storage::EncryptionMethod::RandomSwap)
        .to receive(:available?).and_return(true)
    end

    root = { "mount" => "/", "filesystem" => "ext4", "size" => "max", "create" => true }.freeze
    home = { "mount" => "/home", "filesystem" => "ext4", "size" => "1G", "create" => true }.freeze

    # Issues serialized as the "Issues" D-Bus property does (see
    # Agama::DBus::Storage::Manager#serialize_issues)
    def issues_json
      JSON.parse(serializer.serialize_issues(manager.issues))
    end

    def descriptions
      issues_json.map { |i| i["description"] }
    end

    # Every entry is [text, partitioning]. The (English) text must be one of the issue descriptions
    # that the D-Bus layer would send.
    #
    # The comments are the msgid and the file where it is marked for translation.
    issues = [
      # y2storage/autoinst_issues/missing_root.rb
      [
        "No root partition (/) was found.",
        [{ "device" => "/dev/sda", "use" => "all", "partitions" => [home] }]
      ],
      # y2storage/autoinst_issues/missing_value.rb (missing "use" is detected by the space maker)
      [
        "Missing element 'use'",
        [{ "device" => "/dev/sda", "partitions" => [root] }]
      ],
      # y2storage/autoinst_issues/missing_value.rb (encryption without key)
      [
        "Missing element 'crypt_key'",
        [{
          "device" => "/dev/sda", "use" => "all",
          "partitions" => [root.merge("crypt_method" => "luks1")]
        }]
      ],
      # y2storage/autoinst_issues/invalid_encryption.rb (:unknown)
      [
        "'foo' is not a known encryption method.",
        [{
          "device" => "/dev/sda", "use" => "all",
          "partitions" => [root.merge("crypt_method" => "foo", "crypt_key" => "secret")]
        }]
      ],
      # y2storage/autoinst_issues/invalid_encryption.rb (:unavailable)
      [
        "Encryption method 'pervasive_luks2' is not available in this system.",
        [{
          "device" => "/dev/sda", "use" => "all",
          "partitions" => [root.merge("crypt_method" => "pervasive_luks2", "crypt_key" => "secret")]
        }]
      ],
      # y2storage/autoinst_issues/invalid_encryption.rb (:unsuitable)
      [
        "'random_swap' is not a suitable method to encrypt the device.",
        [{
          "device" => "/dev/sda", "use" => "all",
          "partitions" => [root.merge("crypt_method" => "random_swap")]
        }]
      ],
      # y2storage/autoinst_issues/no_partitionable.rb (with device)
      [
        "The device '/dev/sdb' cannot contain a partition table (gpt requested).",
        [{
          "device" => "/dev/sdb", "type" => :CT_BTRFS, "disklabel" => "gpt",
          "partitions" => [{ "mount" => "/data", "filesystem" => "btrfs", "create" => true }]
        }]
      ],
      # y2storage/autoinst_issues/no_components.rb (Btrfs)
      [
        "Could not find a suitable device for Btrfs filesystem '/dev/sdb'.",
        [{
          "device" => "/dev/sdb", "type" => :CT_BTRFS,
          "partitions" => [{ "mount" => "/data", "filesystem" => "btrfs", "create" => true }]
        }]
      ],
      # y2storage/autoinst_issues/no_components.rb (LVM VG)
      [
        "Could not find a suitable physical volume for volume group 'vg0'.",
        [
          {
            "device" => "/dev/sda", "use" => "all",
            "partitions" => [{ "create" => true, "lvm_group" => "other", "size" => "max" }]
          },
          {
            "device" => "/dev/vg0", "type" => :CT_LVM,
            "partitions" => [root.merge("lv_name" => "root", "size" => "10G")]
          }
        ]
      ],
      # y2storage/autoinst_issues/no_components.rb (RAID)
      [
        "Could not find a suitable member for RAID '/dev/md0'.",
        [{
          "device" => "/dev/md0", "type" => :CT_MD, "raid_options" => { "raid_type" => "raid1" },
          "partitions" => [root]
        }]
      ],
      # y2storage/autoinst_issues/no_components.rb (Bcache)
      [
        "Could not find a backing device for Bcache '/dev/bcache0'.",
        [{ "device" => "/dev/bcache0", "type" => :CT_BCACHE, "partitions" => [root] }]
      ],
      # y2storage/autoinst_issues/multiple_bcache_members.rb (and N_("backing device"))
      [
        "/dev/bcache0: only one backing device can be specified per bcache.",
        [
          {
            "device" => "/dev/sda", "use" => "all",
            "partitions" => [
              { "create" => true, "bcache_backing_for" => "/dev/bcache0", "size" => "10G" },
              { "create" => true, "bcache_backing_for" => "/dev/bcache0", "size" => "10G" }
            ]
          },
          { "device" => "/dev/bcache0", "type" => :CT_BCACHE, "partitions" => [root] }
        ]
      ],
      # y2storage/autoinst_issues/multiple_bcache_members.rb (and N_("caching device"))
      [
        "/dev/bcache0: only one caching device can be specified per bcache.",
        [
          {
            "device" => "/dev/sda", "use" => "all",
            "partitions" => [
              { "create" => true, "bcache_caching_for" => ["/dev/bcache0"], "size" => "10G" },
              { "create" => true, "bcache_caching_for" => ["/dev/bcache0"], "size" => "10G" }
            ]
          },
          { "device" => "/dev/bcache0", "type" => :CT_BCACHE, "partitions" => [root] }
        ]
      ],
      # y2storage/autoinst_issues/thin_pool_not_found.rb
      [
        "Thin pool 'pool0' was not found",
        [
          {
            "device" => "/dev/sda", "use" => "all",
            "partitions" => [{ "create" => true, "lvm_group" => "vg0", "size" => "max" }]
          },
          {
            "device" => "/dev/vg0", "type" => :CT_LVM,
            "partitions" => [
              root.merge("lv_name" => "root", "size" => "10G", "used_pool" => "pool0")
            ]
          }
        ]
      ],
      # y2storage/autoinst_issues/missing_reusable_filesystem.rb (reusing a whole disk)
      [
        "Could not find a reusable filesystem",
        [{
          "device" => "/dev/sda", "disklabel" => "gpt",
          "partitions" => [
            { "partition_nr" => 0, "mount" => "/data", "filesystem" => "ext4", "create" => true }
          ]
        }]
      ]
    ].freeze

    issues.each do |text, partitioning|
      it "returns \"#{text}\" in the description of an issue" do
        manager.configure(legacyAutoyastStorage: partitioning)

        expect(descriptions).to include(text)
      end
    end

    # y2storage/autoinst_issues/unsupported_drive_section.rb
    context "when bcache is used in an architecture different to x86_64" do
      let(:x86_64) { false }

      let(:partitioning) do
        [{ "device" => "/dev/bcache0", "type" => :CT_BCACHE, "partitions" => [root] }]
      end

      it "returns \"A drive of type 'CT_BCACHE' is not supported in this architecture\"" do
        manager.configure(legacyAutoyastStorage: partitioning)

        expect(descriptions)
          .to include("A drive of type 'CT_BCACHE' is not supported in this architecture")
      end
    end
  end

  describe "probing issues (system)" do
    # Issues serialized as the "System" D-Bus property does (see
    # Agama::DBus::Storage::Manager#system_issues_json)
    def system_issues_json
      manager.system_issues.map { |i| serializer.issue_json(i) }
    end

    def descriptions
      system_issues_json.map { |i| i[:description] }
    end

    # y2storage/missing_lvm_pv_issue.rb
    context "when there is an LVM VG with missing PVs" do
      let(:scenario) { "yast2/y2storage/devicegraphs/lvm-errors1-devicegraph.xml" }

      it "returns \"The volume group %{name} is incomplete because some physical volumes are " \
         "missing.\"" do
        expect(descriptions).to include(
          "The volume group /dev/test1 is incomplete because some physical volumes are missing."
        )
      end
    end

    # y2storage/inactive_root_issue.rb
    context "when the root filesystem is not mounted" do
      let(:scenario) { "yast2/y2storage/devicegraphs/mixed_disks.yml" }

      before do
        allow_any_instance_of(Y2Storage::MountPoint).to receive(:active?).and_return(false)
        # The fixture was already probed in the previous before block, probe again with the mock
        mock_storage(devicegraph: scenario)
      end

      it "returns \"The root filesystem looks like not currently mounted.\"" do
        expect(descriptions).to include("The root filesystem looks like not currently mounted.")
      end
    end

    # y2storage/unsupported_bcache_issue.rb
    context "when bcache devices are found in an architecture not supporting them" do
      let(:scenario) { "yast2/y2storage/devicegraphs/bcache2.xml" }
      let(:x86_64) { false }

      it "returns \"Bcache detected, but bcache is not supported on this platform.\"" do
        expect(descriptions)
          .to include("Bcache detected, but bcache is not supported on this platform.")
      end
    end
  end
end
