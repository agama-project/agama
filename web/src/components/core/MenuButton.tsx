import React, { useId, useMemo, useRef } from "react";
import {
  MenuToggle,
  DrilldownMenu,
  MenuContent,
  Divider,
  MenuContainer,
  Menu,
  MenuList,
  MenuItem,
  MenuPopperProps,
  MenuItemProps,
  MenuToggleProps,
} from "@patternfly/react-core";
import { useComboboxKeyboard } from "~/hooks/use-combobox-keyboard";
import { _, TranslatedString } from "~/i18n";
import { useLocation, useNavigate } from "react-router";

/**
 * PatternFly Menu crashes with ids generated by useId.
 *
 * Note that useId is actually generating an identifier that is a valid HTML id attribute but not a
 * valid CSS identifier. Unfortunately, the PatternFly component is querying the node by using the
 * querySelector JavaScript method without escaping the id (e.g., by using CSS.escape).
 */
function useMenuId() {
  const id = useId();
  const menuId = useMemo(() => id.replaceAll(":", ""), [id]);
  return menuId;
}

/**
 * The items of a menu without the dividers that separate nothing: one at
 * either end, or right after another divider.
 *
 * Menus often build their items from conditions, and a divider placed between
 * two groups is left alone when one of the groups turns out empty. Tidying it
 * here keeps every menu from having to work out whether its divider has
 * something on both sides.
 */
function withoutStrayDividers(items: React.ReactNode[]): React.ReactNode[] {
  const isDivider = (item: React.ReactNode) => React.isValidElement(item) && item.type === Divider;
  const tidy: React.ReactNode[] = [];

  items.forEach((item) => {
    if (item === null || item === undefined || item === false) return;
    if (isDivider(item) && (!tidy.length || isDivider(tidy[tidy.length - 1]))) return;
    tidy.push(item);
  });

  while (tidy.length && isDivider(tidy[tidy.length - 1])) tidy.pop();

  return tidy;
}

interface MenuButtonItemProps extends Omit<MenuItemProps, "direction" | "drilldownMenu"> {
  items?: React.ReactNode[];
  /**
   * Choices opening in a menu to the side of this item (a fly-out), rather
   * than replacing the menu (a drill-down, see `items`). The menu holding the
   * item needs `menuProps.hasFlyouts`.
   */
  flyoutItems?: React.ReactNode[];
  /**
   * Marks the item as one of a set of exclusive choices, checked or not, for
   * a menu where one of several options is in effect.
   */
  isChecked?: boolean;
  keepQuery?: boolean;
  upProps?: { label?: TranslatedString };
}

export type CustomToggleProps = {
  onClick?: () => void;
  isExpanded?: boolean;
};

export type MenuButtonProps = {
  items?: React.ReactNode[];
  menuProps?: {
    ["aria-label"]?: TranslatedString;
    ["aria-labelledby"]?: string;
    closeOnClick?: boolean;
    popperProps?: MenuPopperProps;
    /** Whether some of its items open a fly-out (`flyoutItems`). */
    hasFlyouts?: boolean;
  };
  customToggle?: React.ReactElement<CustomToggleProps>;
  toggleProps?: MenuToggleProps;
  /** Disable opening menu with arrow keys when closed */
  disableArrowKeyOpen?: boolean;
};

const MARGIN = 8;

/**
 * Keeps a fly-out inside the window: opening to the left where there is no
 * room on the right (PatternFly's own class for it), and moved up where there
 * is none below. PatternFly measures the fly-out once, before it has its final
 * size, and the variable it moves it up with is not used by its styles, so
 * both are done again here once it is shown.
 */
function keepInView(flyout: HTMLElement) {
  if (flyout.getBoundingClientRect().right > window.innerWidth - MARGIN) {
    flyout.classList.add("pf-m-left");
  }

  const shift = parseFloat(flyout.style.translate.split(" ")[1] || "0") || 0;
  const { top, bottom } = flyout.getBoundingClientRect();
  const overflow = bottom - (window.innerHeight - MARGIN);
  if (overflow <= 0) return;

  /* Never above the top of the window, where nothing could reach it. */
  const up = Math.min(overflow, Math.max(0, top - MARGIN));
  flyout.style.translate = `0 ${shift - up}px`;
}

/**
 * Sets ARIA attributes PatternFly's menu items do not, on the element it
 * renders for the item, and keeps an open fly-out inside the window.
 *
 * - An item opening a fly-out gets no role from PatternFly, only
 *   `aria-haspopup` and `aria-expanded`; the menu pattern asks for a menu
 *   item.
 * - A checked item only gets a check icon; exclusive choices are radio items
 *   that say whether they are checked.
 *
 * @see https://www.w3.org/WAI/ARIA/apg/patterns/menubar/
 */
function useMenuItemAria(
  ref: React.RefObject<HTMLElement>,
  { hasFlyout, isChecked }: { hasFlyout: boolean; isChecked?: boolean },
) {
  React.useEffect(() => {
    const item = ref.current;
    if (!item) return;

    if (isChecked !== undefined) {
      item.setAttribute("role", "menuitemradio");
      item.setAttribute("aria-checked", String(isChecked));
    }

    if (!hasFlyout) return;

    const holder = item.parentElement;
    /* Again on every change: PatternFly renders the item over again as the
       fly-out opens and closes. */
    /* Measured again whenever the fly-out changes size: it opens before
       PatternFly has flipped and laid it out. */
    let sizes: ResizeObserver | undefined;
    const sync = () => {
      item.setAttribute("role", "menuitem");
      sizes?.disconnect();
      const flyout = holder?.querySelector<HTMLElement>(":scope > .pf-v6-c-menu");
      if (!flyout) return;
      sizes = new ResizeObserver(() => keepInView(flyout));
      sizes.observe(flyout);
      requestAnimationFrame(() => requestAnimationFrame(() => keepInView(flyout)));
    };
    sync();
    if (!holder) return;
    const observer = new MutationObserver(sync);
    observer.observe(holder, { childList: true });
    return () => {
      observer.disconnect();
      sizes?.disconnect();
    };
  }, [ref, hasFlyout, isChecked]);
}

export function MenuButtonItem({
  items = [],
  flyoutItems = [],
  isChecked,
  upProps = { label: _("Back") },
  onClick,
  children,
  to,
  keepQuery,
  ...props
}: React.PropsWithChildren<MenuButtonItemProps>): React.ReactNode {
  const itemId = useId();
  const menuId = useMenuId();
  const navigate = useNavigate();
  const location = useLocation();

  const innerRef = React.useRef<HTMLAnchorElement | HTMLButtonElement>(null);
  const hasFlyout = flyoutItems.length > 0;
  useMenuItemAria(innerRef, { hasFlyout, isChecked });

  const onDownClick = (event) => {
    event.stopPropagation();
    onClick && onClick(event);
  };

  if (hasFlyout) {
    return (
      <MenuItem
        itemId={itemId}
        ref={innerRef}
        {...props}
        /* Opens the fly-out rather than choosing anything, so the menu stays
           open. */
        onClick={(event) => event.stopPropagation()}
        flyoutMenu={
          <Menu containsFlyout id={`${itemId}-flyout`}>
            <MenuContent>
              <MenuList aria-label={typeof children === "string" ? children : undefined}>
                {withoutStrayDividers(flyoutItems)}
              </MenuList>
            </MenuContent>
          </Menu>
        }
      >
        {children}
      </MenuItem>
    );
  }

  if (!items.length) {
    return (
      <MenuItem
        itemId={itemId}
        ref={innerRef}
        isSelected={isChecked}
        onClick={() => {
          onClick && onClick();
          to && navigate({ pathname: to, search: keepQuery ? location.search : "" });
        }}
        {...props}
      >
        {children}
      </MenuItem>
    );
  }
  return (
    <MenuItem
      itemId={itemId}
      {...props}
      onClick={onDownClick}
      direction="down"
      drilldownMenu={
        <DrilldownMenu id={menuId}>
          <MenuItem direction="up" onClick={(e) => e.stopPropagation()}>
            {upProps.label}
          </MenuItem>
          <Divider />
          {withoutStrayDividers(items)}
        </DrilldownMenu>
      }
    >
      {children}
    </MenuItem>
  );
}

/**
 * Dropdown menu button with support for drilldown menus and keyboard navigation.
 *
 * Uses {@link useComboboxKeyboard} hook for arrow-key-to-open behavior: pressing ↓/↑
 * on a closed toggle opens the menu and focuses the first/last item.
 */
export default function MenuButton({
  items = [],
  menuProps = {},
  toggleProps = {},
  customToggle,
  disableArrowKeyOpen = false,
  children,
}: React.PropsWithChildren<MenuButtonProps>): React.ReactNode {
  const pfToggleRef = useRef();
  const rootId = useMenuId();
  const { isOpen, setIsOpen, menuRef, getToggleRef, onToggleKeydown } = useComboboxKeyboard({
    component: "menu",
  });
  const [menuDrilledIn, setMenuDrilledIn] = React.useState<string[]>([]);
  const [drilldownPath, setDrilldownPath] = React.useState<string[]>([]);
  const [activeMenu, setActiveMenu] = React.useState<string>(rootId);
  const [activeItemId, setActiveItemId] = React.useState("");
  const [menuHeights, setMenuHeights] = React.useState({});

  menuProps = { popperProps: {}, closeOnClick: true, ...menuProps };

  const resetState = () => {
    setMenuDrilledIn([]);
    setDrilldownPath([]);
    setActiveMenu(rootId);
    // Reset the height of the root menu. Otherwise, the memorized height could be wrong if the
    // items of the root menu change.
    if (!isOpen) setMenuHeights({ ...menuHeights, [rootId]: undefined });
  };

  const onOpenChange = (nextState) => {
    setIsOpen(nextState);
  };

  const toggle = () => {
    resetState();
    setIsOpen(!isOpen);
  };

  const drillIn = (
    _: React.KeyboardEvent | React.MouseEvent,
    fromMenuId: string,
    toMenuId: string,
    pathId: string,
  ) => {
    setMenuDrilledIn([...menuDrilledIn, fromMenuId]);
    setDrilldownPath([...drilldownPath, pathId]);
    setActiveMenu(toMenuId);
    setActiveItemId(pathId);
  };

  const drillOut = (_: React.KeyboardEvent | React.MouseEvent, toMenuId: string) => {
    const menuDrilledInSansLast = menuDrilledIn.slice(0, menuDrilledIn.length - 1);
    const pathSansLast = drilldownPath.slice(0, drilldownPath.length - 1);
    const lastPath = [...pathSansLast].pop();
    setMenuDrilledIn(menuDrilledInSansLast);
    setDrilldownPath(pathSansLast);
    setActiveMenu(toMenuId);
    setActiveItemId(lastPath);
  };

  const setHeight = (menuId: string, height: number) => {
    // FIXME: look for a better way to avoid test crashing because of this method
    if (process.env.NODE_ENV === "test") return;

    if (
      menuHeights[menuId] === undefined ||
      (menuId !== rootId && menuHeights[menuId] !== height)
    ) {
      setMenuHeights({ ...menuHeights, [menuId]: height });
    }
  };

  const baseToggleProps = {
    ref: getToggleRef(pfToggleRef),
    onClick: toggle,
    onKeyDown: disableArrowKeyOpen ? undefined : onToggleKeydown,
    isExpanded: isOpen,
  };

  return (
    <MenuContainer
      isOpen={isOpen}
      onOpenChange={onOpenChange}
      toggleRef={pfToggleRef}
      popperProps={{
        direction: "down",
        /* Opens upward where there is no room below. PatternFly's default
           falls back to the placement opposite the one asked for, on the same
           side; listing placements instead leaves only those to try. */
        enableFlip: true,
        ...menuProps.popperProps,
      }}
      toggle={
        React.isValidElement(customToggle) ? (
          React.cloneElement(customToggle as React.ReactElement, baseToggleProps)
        ) : (
          <MenuToggle {...baseToggleProps} {...toggleProps}>
            {children}
          </MenuToggle>
        )
      }
      menuRef={menuRef}
      menu={
        <Menu
          id={rootId}
          /* Not both: a drill-down menu hides whatever reaches past its edges,
             which is where a fly-out opens. */
          containsDrilldown={!menuProps.hasFlyouts}
          containsFlyout={menuProps.hasFlyouts}
          onDrillIn={drillIn}
          onDrillOut={drillOut}
          onGetMenuHeight={setHeight}
          activeMenu={activeMenu}
          activeItemId={activeItemId}
          drilledInMenus={menuDrilledIn}
          drilldownItemPath={drilldownPath}
          ref={menuRef}
          onClick={() => menuProps.closeOnClick && setIsOpen(false)}
        >
          <MenuContent menuHeight={`${menuHeights[activeMenu]}px`}>
            <MenuList
              aria-label={menuProps["aria-label"]}
              aria-labelledby={menuProps["aria-labelledby"]}
            >
              {withoutStrayDividers(items)}
            </MenuList>
          </MenuContent>
        </Menu>
      }
    />
  );
}
MenuButton.Item = MenuButtonItem;
